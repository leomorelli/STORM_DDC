% Load a Python-generated Stage A.9 v7.3 checkpoint without running MCMC.
% Set python_checkpoint_path before running, or place the generated checkpoint
% beside this script as python_generated_checkpoint.mat.

if ~exist('python_checkpoint_path', 'var')
    python_checkpoint_path = fullfile(fileparts(mfilename('fullpath')), ...
        'python_generated_checkpoint.mat');
end

checkpoint_loaded = false;
load_error_identifier = '';
load_error_message = '';
required_variables_exist = false;
finish_runs_state_complete = false;
finish_runs_input_state_complete = false;
finish_runs_signature_compatible = false;
cell_contract = false;
probability_struct_contract = false;
sparse_contract = false;
dscale_dense_contract = false;
variable_metadata = struct([]);

try
    load(python_checkpoint_path);
    checkpoint_loaded = true;

    required = {'LocalizationsFinal','Frame_Information','TrueLocalizations', ...
        'Photons','Final_Loc_Blinking_Corrected', ...
        'Final_Frame_Blinking_Corrected','Trajectory_of_Localizations', ...
        'Constantf','Constantf2','Orderf','Step','Lik','RelScore', ...
        'Numb_of_Loc','Prob_dists','bins','Distribution_for_Blink', ...
        'Resolution','X_overall','M_mat','stepper','N_f', ...
        'Photon_weighted_Correction','timer','addonarray'};
    required_variables_exist = all(cellfun(@(name) exist(name,'var') == 1, required));

    cell_contract = iscell(LocalizationsFinal) && iscell(Frame_Information) && ...
        iscell(TrueLocalizations) && iscell(Photons) && ...
        iscell(Final_Loc_Blinking_Corrected) && ...
        iscell(Final_Frame_Blinking_Corrected) && ...
        iscell(Trajectory_of_Localizations) && iscell(Prob_dists);

    if ~isempty(Prob_dists)
        probability_struct_contract = isstruct(Prob_dists{1}) && ...
            all(isfield(Prob_dists{1}, {'Deviation_in_Probability', ...
                'Prob_Distributions','Dscale_store'}));
        if probability_struct_contract
            sparse_contract = issparse(Prob_dists{1}.Deviation_in_Probability) && ...
                issparse(Prob_dists{1}.Prob_Distributions);
            dscale_dense_contract = isnumeric(Prob_dists{1}.Dscale_store) && ...
                ~issparse(Prob_dists{1}.Dscale_store);
        end
    end

    % These are the variables consumed directly by Finish_Runs before/at the
    % DDC_MCMC call. Merely check availability; do not execute the long MCMC.
    finish_required = {'Step','stepper','LocalizationsFinal','Frame_Information', ...
        'N_f','Resolution','TrueLocalizations','bins', ...
        'Distribution_for_Blink','timer','Constantf','Orderf','Lik', ...
        'RelScore','Numb_of_Loc','Prob_dists','addonarray','Constantf2', ...
        'X_overall','M_mat'};
    finish_runs_state_complete = all(cellfun( ...
        @(name) exist(name,'var') == 1, finish_required));
    finish_runs_input_state_complete = finish_runs_state_complete;
    % Input completeness is not execution compatibility. Current Finish_Runs
    % requests 11 outputs from the 12-output DDC_MCMC (BUG-007).
    finish_runs_signature_compatible = false;

    details = whos;
    variable_metadata = repmat(struct('name','','class','','size',[]), numel(details), 1);
    for index = 1:numel(details)
        variable_metadata(index).name = details(index).name;
        variable_metadata(index).class = details(index).class;
        variable_metadata(index).size = details(index).size;
    end
catch ME
    load_error_identifier = ME.identifier;
    load_error_message = ME.message;
end

save(fullfile(fileparts(mfilename('fullpath')), ...
    'checkpoint_compatibility_reference.mat'), ...
    'checkpoint_loaded','load_error_identifier','load_error_message', ...
    'required_variables_exist','finish_runs_state_complete', ...
    'finish_runs_input_state_complete','finish_runs_signature_compatible', ...
    'cell_contract', ...
    'probability_struct_contract','sparse_contract','dscale_dense_contract', ...
    'variable_metadata','-v7');
