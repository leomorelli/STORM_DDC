class DDCSourceBug007(RuntimeError):
    """The stale Finish_Runs output assignment reached its numeric struct access."""


class DDCSourceResumeBlockedByEarlierDefect(RuntimeError):
    """Repository integer frames can fail inside DDC_MCMC before BUG-007."""


def make_analyzed_filename(source_filename: str, *, on_date: date | None = None) -> str:
    """Port ``Analyzed_Time`` + ``datestr(datetime('today'))`` + filename."""

    selected = date.today() if on_date is None else on_date
    stamp = f"{selected.day:02d}-{_MATLAB_MONTHS[selected.month - 1]}-{selected.year:04d}"
    return f"Analyzed_Time{stamp}_{Path(source_filename).name}"


@dataclass(frozen=True)
class DDCCheckpoint:
    """Typed checkpoint containing the state consumed by MATLAB ``Finish_Runs``."""

    dataset: DDCDataset
    config: DDCConfig
    result: DDCPipelineResult
    analyzed_filename: str
    source_filename: str | None = None
    source_metadata: dict[str, Any] = field(default_factory=dict)
    phase: str = "outer"

    @classmethod
    def from_result(
        cls,
        result: DDCPipelineResult,
        dataset: DDCDataset,
        config: DDCConfig,
        analyzed_filename: str,
        *,
        source_filename: str | None = None,
        source_metadata: Mapping[str, Any] | None = None,
        phase: str = "outer",
    ) -> "DDCCheckpoint":
        checkpoint_dataset = DDCDataset(
            localizations=[value.copy() for value in result.working_localizations],
            frames=[value.copy() for value in result.frames],
            true_localizations=[value.copy() for value in result.true_localizations],
            photons=[value.copy() for value in result.photons],
            came_from_image=(
                None if dataset.came_from_image is None
                else dataset.came_from_image.copy()
            ),
            addon=None if dataset.addon is None else dataset.addon.copy(),
            cuts=tuple(
                None if cells is None else [value.copy() for value in cells]
                for cells in dataset.cuts
            ),
            parameters_to_split=(
                None if dataset.parameters_to_split is None
                else [value.copy() for value in dataset.parameters_to_split]
            ),
            source=dataset.source,
            mat_passthrough=dict(dataset.mat_passthrough),
        )
        return cls(
            dataset=checkpoint_dataset,
            config=config,
            result=result,
            analyzed_filename=analyzed_filename,
            source_filename=source_filename,
            source_metadata=dict(source_metadata or {}),
            phase=phase,
        )


def _row(value: ArrayLike) -> NDArray[Any]:
    return np.asarray(value).reshape(1, -1, order="F")


def _cell(values: Sequence[ArrayLike], *, vector_cells: bool = False) -> NDArray[Any]:
    result = np.empty((1, len(values)), dtype=object)
    for index, value in enumerate(values):
        array = np.asarray(value)
        if vector_cells:
            array = _row(array)
        result[0, index] = array
    return result


def _optional_cell(
    values: Sequence[NDArray[Any] | None], *, vector_cells: bool = False
) -> NDArray[Any]:
    last = max((i for i, value in enumerate(values) if value is not None), default=-1)
    if last < 0:
        return np.empty((0, 0), dtype=object)
    materialized: list[NDArray[Any]] = []
    for value in values[: last + 1]:
        if value is None:
            materialized.append(np.empty((0, 0), dtype=np.float64))
        else:
            materialized.append(np.asarray(value))
    return _cell(materialized, vector_cells=vector_cells)


def _probability_structs(
    states: Sequence[DDCImageState], *, sparse_on_disk: bool
) -> NDArray[Any]:
    result = np.empty((1, len(states)), dtype=object)
    for index, state in enumerate(states):
        cache = state.probability_cache
        # hdf5storage writes dense placeholders. The v7.3 writer replaces the
        # two active fields with MATLAB sparse groups after schema generation.
        result[0, index] = {
            "Deviation_in_Probability": np.asarray(
                cache.deviation_in_probability, dtype=np.float64
            ),
            "Prob_Distributions": np.asarray(
                cache.prob_distributions, dtype=np.float64
            ),
            "Dscale_store": _row(cache.dscale_store),
        }
    return result


_PRIMARY_VARIABLES = {
    "LocalizationsFinal", "Frame_Information", "TrueLocalizations", "Photons",
    "Came_from_image", "addonarray", "cut1array", "cut2array", "cut3array",
    "Parameters_to_split", "Resolution", "stepper", "N_f",
    "Photon_weighted_Correction", "timer", "bins", "Distribution_for_Blink",
    "X_overall", "M_mat", "Constantf", "Constantf2", "Orderf", "Step", "Lik",
    "RelScore", "Numb_of_Loc", "Prob_dists", "Final_Loc_Blinking_Corrected",
    "Final_Frame_Blinking_Corrected", "Trajectory_of_Localizations", "String",
    "filename", "pathname", "full_filename", "cluster",
}


def checkpoint_matlab_variables(checkpoint: DDCCheckpoint) -> dict[str, Any]:
    """Map typed Python state to exact active MATLAB workspace names."""

    dataset = checkpoint.dataset
    result = checkpoint.result
    states = result.states
    variables = dict(dataset.mat_passthrough)
    variables.update(
        {
            "LocalizationsFinal": _cell(result.working_localizations),
            "Frame_Information": _cell(result.frames, vector_cells=True),
            "TrueLocalizations": _cell(result.true_localizations),
            "Photons": _cell(result.photons, vector_cells=True),
            "Resolution": np.array([[result.resolution]], dtype=np.float64),
            "stepper": np.array([[checkpoint.config.stepper]], dtype=np.float64),
            "N_f": np.array([[checkpoint.config.n_f]], dtype=np.float64),
            "Photon_weighted_Correction": np.array(
                [[checkpoint.config.photon_weighted_correction]], dtype=np.float64
            ),
            "timer": np.array([[checkpoint.config.timer]], dtype=np.float64),
            "bins": _row(result.bins),
            "Distribution_for_Blink": _row(result.distribution_for_blink),
            "X_overall": _row(result.x_overall),
            "M_mat": np.asarray(result.m_mat),
            "Constantf": _cell([state.constantf for state in states], vector_cells=True),
            "Constantf2": _cell([state.constant2ft for state in states], vector_cells=True),
            "Orderf": _cell(
                [state.orderf.astype(np.float64) for state in states], vector_cells=True
            ),
            "Step": _row(np.asarray([state.step for state in states], dtype=np.float64)),
            "Lik": _cell([state.likelihood for state in states], vector_cells=True),
            "RelScore": _cell([state.score for state in states], vector_cells=True),
            "Numb_of_Loc": _cell(
                [state.number_of_localizations for state in states], vector_cells=True
            ),
            "Prob_dists": _probability_structs(
                states, sparse_on_disk=checkpoint.phase != "initial"
            ),
            "Final_Loc_Blinking_Corrected": _optional_cell(
                result.final_localizations
            ),
            "Final_Frame_Blinking_Corrected": _optional_cell(
                result.final_frames, vector_cells=True
            ),
            "Trajectory_of_Localizations": _optional_cell(
                result.trajectories, vector_cells=True
            ),
            "String": checkpoint.analyzed_filename,
        }
    )

    addon = dataset.addon
    if addon is None:
        addon = np.zeros(500, dtype=np.float64)
    variables["addonarray"] = _row(addon)
    optional_values = {
        "Came_from_image": dataset.came_from_image,
        "cut1array": dataset.cuts[0],
        "cut2array": dataset.cuts[1],
        "cut3array": dataset.cuts[2],
        "Parameters_to_split": dataset.parameters_to_split,
    }
    for name, value in optional_values.items():
        if value is None:
            continue
        if isinstance(value, list):
            variables[name] = _cell(value, vector_cells=True)
        else:
            variables[name] = _row(value)

    if checkpoint.source_filename is not None:
        variables["filename"] = checkpoint.source_filename
    for name, value in checkpoint.source_metadata.items():
        if name not in _PRIMARY_VARIABLES or name in {
            "pathname", "full_filename", "cluster"
        }:
            variables[name] = value
    return variables


def _atomic_target(path: Path) -> tuple[Path, int]:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    os.close(descriptor)
    return Path(temporary), descriptor


def _atomic_write(path: Path, write: Any) -> None:
    temporary, _ = _atomic_target(path)
    try:
        write(temporary)
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def save_initial_checkpoint(checkpoint: DDCCheckpoint, path: str | Path) -> Path:
    """Write the source's first pre-v7.3 MATLAB v5 checkpoint atomically."""

    destination = Path(path)
    variables = checkpoint_matlab_variables(checkpoint)

    def write(temporary: Path) -> None:
        savemat(
            temporary,
            variables,
            appendmat=False,
            format="5",
            long_field_names=True,
            do_compression=False,
            oned_as="row",
        )

    _atomic_write(destination, write)
    return destination


def _write_sparse_group(parent: h5py.Group, name: str, matrix: NDArray[Any]) -> None:
    csc = sparse.csc_matrix(np.asarray(matrix, dtype=np.float64))
    if name in parent:
        del parent[name]
    group = parent.create_group(name)
    group.attrs["H5PATH"] = np.bytes_(parent.name)
    group.attrs["MATLAB_class"] = np.bytes_("double")
    group.attrs["MATLAB_sparse"] = np.uint64(csc.shape[0])
    group.create_dataset("data", data=csc.data.astype(np.float64, copy=False))
    group.create_dataset("ir", data=csc.indices.astype(np.uint64, copy=False))
    group.create_dataset("jc", data=csc.indptr.astype(np.uint64, copy=False))


def _patch_probability_sparse(path: Path, states: Sequence[DDCImageState]) -> None:
    with h5py.File(path, "r+") as handle:
        references = handle["Prob_dists"]
        for index, state in enumerate(states):
            # An untouched ineligible image retains the source's dense empty
            # fields. A processed image was explicitly passed through sparse().
            processed = bool(
                state.likelihood.size
                or state.probability_cache.deviation_in_probability.size
                or state.probability_cache.prob_distributions.size
            )
            if not processed:
                continue
            reference = references[index, 0]
            struct_group = handle[reference]
            _write_sparse_group(
                struct_group,
                "Deviation_in_Probability",
                state.probability_cache.deviation_in_probability,
            )
            _write_sparse_group(
                struct_group,
                "Prob_Distributions",
                state.probability_cache.prob_distributions,
            )


def save_v73_checkpoint(checkpoint: DDCCheckpoint, path: str | Path) -> Path:
    """Write a MATLAB-compatible v7.3 checkpoint atomically."""

    destination = Path(path)
    variables = checkpoint_matlab_variables(checkpoint)

    def write(temporary: Path) -> None:
        hdf5storage.savemat(
            temporary,
            variables,
            appendmat=False,
            fmt="7.3",
            oned_as="column",
            store_python_metadata=False,
            action_for_matlab_incompatible="error",
            truncate_existing=True,
        )
        _patch_probability_sparse(temporary, checkpoint.result.states)

    _atomic_write(destination, write)
    return destination


class CheckpointWriter:
    """Pipeline callback implementing initial-v5 then iterative-v7.3 saves."""

    def __init__(
        self,
        path: str | Path,
        dataset: DDCDataset,
        config: DDCConfig,
        *,
        analyzed_filename: str | None = None,
        source_metadata: Mapping[str, Any] | None = None,
    ) -> None:
        self.path = Path(path)
        self.dataset = dataset
        self.config = config
        source_filename = dataset.source.name if dataset.source is not None else None
        self.source_filename = source_filename
        self.analyzed_filename = analyzed_filename or (
            make_analyzed_filename(source_filename)
            if source_filename is not None else self.path.name
        )
        metadata = dict(source_metadata or {})
        if dataset.source is not None:
            metadata.setdefault("pathname", str(dataset.source.parent) + os.sep)
            metadata.setdefault("full_filename", str(dataset.source))
        metadata.setdefault("cluster", np.array([[0.0]]))
        self.source_metadata = metadata
        self.last_checkpoint: DDCCheckpoint | None = None

    def __call__(self, result: DDCPipelineResult, phase: str) -> None:
        checkpoint = DDCCheckpoint.from_result(
            result,
            self.dataset,
            self.config,
            self.analyzed_filename,
            source_filename=self.source_filename,
            source_metadata=self.source_metadata,
            phase=phase,
        )
        if phase == "initial":
            save_initial_checkpoint(checkpoint, self.path)
        elif phase == "outer":
            save_v73_checkpoint(checkpoint, self.path)
        else:
            raise ValueError(f"unknown checkpoint phase: {phase}")
        self.last_checkpoint = checkpoint


def _is_hdf5(path: Path) -> bool:
    # MATLAB v7.3 places an HDF5 user block before the HDF5 signature.
    return bool(h5py.is_hdf5(path))


def _flatten_cell(data: Mapping[str, Any], name: str) -> list[NDArray[Any]]:
    value = np.asarray(data[name])
    if value.dtype != object:
        if value.size == 0:
            return []
        raise ValueError(f"checkpoint variable {name} is not a MATLAB cell")
    return [np.asarray(cell) for cell in value.ravel(order="F")]


def _vectors(data: Mapping[str, Any], name: str) -> list[NDArray[Any]]:
    return [value.reshape(-1, order="F") for value in _flatten_cell(data, name)]


def _optional_outputs(
    data: Mapping[str, Any], name: str, n_images: int, *, vectors: bool = False
) -> list[NDArray[Any] | None]:
    cells = _flatten_cell(data, name)
    result: list[NDArray[Any] | None] = [None] * n_images
    for index, value in enumerate(cells[:n_images]):
        if value.size:
            result[index] = value.reshape(-1, order="F") if vectors else value
    return result


def _scalar(data: Mapping[str, Any], name: str) -> float:
    return float(np.asarray(data[name]).reshape(-1, order="F")[0])


def _matlab_string(value: Any) -> str:
    array = np.asarray(value)
    if array.dtype.kind in {"U", "S"}:
        return "".join(str(item) for item in array.ravel(order="F"))
    if np.issubdtype(array.dtype, np.integer):
        return "".join(chr(int(item)) for item in array.ravel(order="F"))
    if array.dtype == object and array.size == 1:
        return str(array.item())
    return str(value)


def _dense_sparse_group(group: h5py.Group) -> NDArray[np.float64]:
    rows = int(group.attrs["MATLAB_sparse"])
    data = np.asarray(group["data"], dtype=np.float64)
    indices = np.asarray(group["ir"], dtype=np.int64)
    indptr = np.asarray(group["jc"], dtype=np.int64)
    columns = max(indptr.size - 1, 0)
    return sparse.csc_matrix((data, indices, indptr), shape=(rows, columns)).toarray()


def _v73_probability_caches(path: Path, n_images: int) -> list[ProbabilityCache]:
    caches: list[ProbabilityCache] = []
    with h5py.File(path, "r") as handle:
        refs = handle["Prob_dists"]
        for index in range(n_images):
            struct_group = handle[refs[index, 0]]
            matrices: list[NDArray[np.float64]] = []
            for field_name in (
                "Deviation_in_Probability", "Prob_Distributions"
            ):
                item = struct_group[field_name]
                if isinstance(item, h5py.Group) and "MATLAB_sparse" in item.attrs:
                    matrices.append(_dense_sparse_group(item))
                elif "MATLAB_empty" in item.attrs:
                    dimensions = tuple(
                        int(value) for value in np.asarray(item)[::-1]
                    )
                    matrices.append(np.empty(dimensions, dtype=np.float64))
                else:
                    matrices.append(np.asarray(item).T.copy())
            dscale_item = struct_group["Dscale_store"]
            dscale = (
                np.empty(0, dtype=np.float64)
                if "MATLAB_empty" in dscale_item.attrs
                else np.asarray(dscale_item).reshape(-1, order="F")
            )
            caches.append(ProbabilityCache(matrices[0], matrices[1], dscale))
    return caches


def _v5_probability_caches(data: Mapping[str, Any], n_images: int) -> list[ProbabilityCache]:
    cells = np.asarray(data["Prob_dists"]).ravel(order="F")
    caches: list[ProbabilityCache] = []
    for index in range(n_images):
        item = cells[index]
        if isinstance(item, np.ndarray) and item.size == 1:
            item = item.item()
        def field_value(name: str) -> NDArray[Any]:
            if hasattr(item, name):
                return np.asarray(getattr(item, name))
            if isinstance(item, np.void):
                return np.asarray(item[name])
            raise ValueError(f"Prob_dists struct lacks {name}")
        caches.append(
            ProbabilityCache(
                field_value("Deviation_in_Probability"),
                field_value("Prob_Distributions"),
                field_value("Dscale_store").reshape(-1, order="F"),
            )
        )
    return caches


def load_checkpoint(path: str | Path) -> DDCCheckpoint:
    """Load a Python-generated initial or iterative DDC checkpoint."""

    source = Path(path)
    v73 = _is_hdf5(source)
    data = (
        hdf5storage.loadmat(source)
        if v73 else loadmat(source, squeeze_me=False, struct_as_record=False)
    )
    localizations = _flatten_cell(data, "LocalizationsFinal")
    n_images = len(localizations)
    frames = _vectors(data, "Frame_Information")
    truth = _flatten_cell(data, "TrueLocalizations")
    photons = _vectors(data, "Photons")
    steps = np.asarray(data["Step"]).reshape(-1, order="F")
    constantf = _vectors(data, "Constantf")
    constantf2 = _vectors(data, "Constantf2")
    orderf = _vectors(data, "Orderf")
    likelihood = _vectors(data, "Lik")
    scores = _vectors(data, "RelScore")
    counts = _vectors(data, "Numb_of_Loc")
    caches = (
        _v73_probability_caches(source, n_images)
        if v73 else _v5_probability_caches(data, n_images)
    )
    states = [
        DDCImageState(
            step=int(steps[index]),
            constantf=constantf[index].astype(np.float64, copy=False),
            constant2ft=constantf2[index].astype(np.float64, copy=False),
            orderf=orderf[index].astype(np.int64),
            likelihood=likelihood[index].astype(np.float64, copy=False),
            score=scores[index].astype(np.float64, copy=False),
            number_of_localizations=counts[index].astype(np.float64, copy=False),
            probability_cache=caches[index],
        )
        for index in range(n_images)
    ]
    config = DDCConfig(
        resolution=_scalar(data, "Resolution"),
        stepper=int(_scalar(data, "stepper")),
        n_f=int(_scalar(data, "N_f")),
        photon_weighted_correction=int(_scalar(data, "Photon_weighted_Correction")),
        timer=_scalar(data, "timer"),
    )
    represented = set(_PRIMARY_VARIABLES)
    passthrough = {
        name: value
        for name, value in data.items()
        if not name.startswith("__") and name not in represented
    }
    def optional_vector(name: str) -> NDArray[Any] | None:
        if name not in data:
            return None
        return np.asarray(data[name]).reshape(-1, order="F")
    def optional_cells(name: str) -> list[NDArray[Any]] | None:
        return _flatten_cell(data, name) if name in data else None
    metadata = {
        name: data[name]
        for name in ("pathname", "full_filename", "cluster", "Location")
        if name in data
    }
    source_filename = _matlab_string(data["filename"]) if "filename" in data else None
    dataset = DDCDataset(
        localizations=localizations,
        frames=frames,
        true_localizations=truth,
        photons=photons,
        came_from_image=optional_vector("Came_from_image"),
        addon=optional_vector("addonarray"),
        cuts=(optional_cells("cut1array"), optional_cells("cut2array"), optional_cells("cut3array")),
        parameters_to_split=optional_cells("Parameters_to_split"),
        source=None,
        mat_passthrough=passthrough,
    )
    result = DDCPipelineResult(
        final_localizations=_optional_outputs(
            data, "Final_Loc_Blinking_Corrected", n_images
        ),
        final_frames=_optional_outputs(
            data, "Final_Frame_Blinking_Corrected", n_images, vectors=True
        ),
        trajectories=_optional_outputs(
            data, "Trajectory_of_Localizations", n_images, vectors=True
        ),
        states=states,
        working_localizations=[value.copy() for value in localizations],
        frames=[value.copy() for value in frames],
        true_localizations=[value.copy() for value in truth],
        photons=[value.copy() for value in photons],
        bins=np.asarray(data["bins"]).reshape(-1, order="F"),
        distribution_for_blink=np.asarray(data["Distribution_for_Blink"]).reshape(-1, order="F"),
        resolution=config.resolution,
        x_overall=np.asarray(data["X_overall"]).reshape(-1, order="F"),
        m_mat=np.asarray(data["M_mat"]),
        diagnostics=(),
    )
    analyzed_filename = _matlab_string(data["String"])
    return DDCCheckpoint(
        dataset=dataset,
        config=config,
        result=result,
        analyzed_filename=analyzed_filename,
        source_filename=source_filename,
        source_metadata=metadata,
        phase="outer" if v73 else "initial",
    )


def resume_ddc(
    checkpoint: DDCCheckpoint,
    *,
    rngs: Sequence[RNGLike] | None = None,
    checkpoint_callback: CheckpointCallback | None = None,
    workers: int = 1,
    verbose: bool = False,
) -> DDCPipelineResult:
    """Run a corrected Python continuation using the current Stage-A contract.

    This deliberately does not reproduce the obsolete eleven-output assignment
    in the repository's ``Finish_Runs.m``.  It reloads the same saved state but
    calls the modern Python MCMC interface without recomputing the shared
    blinking distribution.
    """

    return run_ddc(
        checkpoint.dataset,
        checkpoint.config,
        rngs=rngs,
        checkpoint_callback=checkpoint_callback,
        resume_from=checkpoint.result,
        workers=workers,
        verbose=verbose,
    )


def resume_finish_runs_source(checkpoint: DDCCheckpoint) -> DDCPipelineResult:
    """Represent the active MATLAB ``Finish_Runs`` control flow faithfully.

    Completed checkpoints are no-ops.  Unfinished images whose MATLAB
    ``length(LocalizationsFinal{i})`` is at most ten are marked complete.  An
    eligible floating-frame image reaches the stale eleven-output call and then
    raises :class:`DDCSourceBug007`: output 10 is numeric ``Orderf``, so the
    following ``Prob_dists2.Deviation_in_Probability`` access cannot succeed.

    Integer-frame checkpoints are reported separately because documented
    source defects can fail inside ``DDC_MCMC`` before it returns, masking the
    post-return signature defect.  This diagnostic API never substitutes the
    corrected continuation and never runs stochastic MCMC.
    """

    result = copy.deepcopy(checkpoint.result)
    stepper = checkpoint.config.stepper
    for locations, frames, state in zip(
        result.working_localizations, result.frames, result.states, strict=True
    ):
        if state.step >= stepper:
            continue
        matlab_length = max(np.asarray(locations).shape, default=0)
        if matlab_length <= 10:
            state.step = stepper
            continue
        if np.issubdtype(np.asarray(frames).dtype, np.integer):
            raise DDCSourceResumeBlockedByEarlierDefect(
                "DDC-SOURCE-BUG-007 is not yet observable: integer frames can "
                "fail inside DDC_MCMC through DDC-SOURCE-BUG-001/002/003/004 "
                "before the stale Finish_Runs output assignment returns."
            )
        raise DDCSourceBug007(
            "DDC-SOURCE-BUG-007: Finish_Runs requests 11 outputs from the "
            "current 12-output DDC_MCMC. Prob_dists2 receives numeric Orderf, "
            "so Prob_dists2.Deviation_in_Probability is invalid; Constant2ft "
            "is discarded."
        )
    return result


